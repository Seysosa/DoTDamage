function Locale.code(env)
    local state = env.DoTDamageState
    local selected = type(state) == "table" and type(state.settings) == "table" and state.settings.uiLanguage
    if selected == "deDE" or selected == "enUS" or selected == "frFR" or selected == "esES" then return selected end
    local client = type(env.GetLocale) == "function" and env.GetLocale() or "enUS"
    if client == "esMX" then return "esES" end
    if client == "deDE" or client == "frFR" or client == "esES" then return client end
    return "enUS"
end
function Locale.create(env)
    return function(key, ...)
        key = LEGACY[key] or key
        local code = Locale.code(env)
        local translations = namespace and namespace.UITranslations
        local text = code == "deDE" and DE[key] or translations and translations[code] and translations[code].labels[key] or key
        text = text or key
        if select("#", ...) > 0 then return string.format(text, ...) end
        return text
    end
end
if type(namespace) == "table" then namespace.UILocale = Locale end
return Locale
